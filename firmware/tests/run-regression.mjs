#!/usr/bin/env node
/*
 * Regression tests for the corrected logic in firmware/aqsms_esp32/aqsms_esp32.ino
 * ===========================================================================
 *
 * WHAT THIS DOES
 *   1. Reads aqsms_esp32.ino and extracts the region between
 *      "/* @AQSMS-PURE-BEGIN *\/" and "/* @AQSMS-PURE-END *\/", plus the SMS_/SIM_
 *      defines, the event-id limits and struct CdsReport that region depends on.
 *   2. Compiles that extracted text to a wasm32 module and instantiates it.
 *   3. Runs assertions against it and prints the results.
 *
 * WHY IT IS BUILT THIS WAY
 *   The functions under test are NOT re-implemented here.  The bytes compiled
 *   and executed are the bytes shipped in the sketch, so a change to the sketch
 *   is a change to the test — there is no second copy to drift out of sync.
 *
 *   There is no host C/C++ toolchain on this machine: no gcc, no g++, no cl.exe,
 *   and the Android NDK's clang has no Windows sysroot to link against.  What
 *   the NDK *can* do is emit freestanding wasm32, and Node can run that.  The
 *   pure region is deliberately dependency-free (no Arduino, no libc) so that
 *   this works.
 *
 * WHAT THIS DOES NOT COVER
 *   Anything requiring the ESP32, the modem, a SIM, a sensor or the Pi.  Every
 *   hardware behaviour remains untested until it is tested on hardware.
 *
 * USAGE
 *   node firmware/tests/run-regression.mjs
 *   AQSMS_CLANG=/path/to/clang++ node firmware/tests/run-regression.mjs
 *   AQSMS_KEEP=1 ...   keep the generated sources for inspection
 */

import { readFileSync, writeFileSync, mkdtempSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const INO = resolve(HERE, '..', 'aqsms_esp32', 'aqsms_esp32.ino');

// ---------------------------------------------------------------------------
// 1. Locate a clang++ that can target wasm32.
// ---------------------------------------------------------------------------
function findClang() {
    if (process.env.AQSMS_CLANG && existsSync(process.env.AQSMS_CLANG)) {
        return process.env.AQSMS_CLANG;
    }
    const sdkRoots = [
        process.env.ANDROID_HOME,
        process.env.ANDROID_SDK_ROOT,
        'C:\\Android\\Sdk',
        join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk'),
    ].filter(Boolean);

    for (const root of sdkRoots) {
        const ndkRoot = join(root, 'ndk');
        if (!existsSync(ndkRoot)) continue;
        for (const ver of readdirSync(ndkRoot).sort().reverse()) {
            const cand = join(ndkRoot, ver, 'toolchains', 'llvm', 'prebuilt',
                              'windows-x86_64', 'bin', 'clang++.exe');
            if (existsSync(cand)) return cand;
        }
    }
    // Last resort: whatever is on PATH.
    return 'clang++';
}

// ---------------------------------------------------------------------------
// 2. Extract the code under test, verbatim, from the sketch.
// ---------------------------------------------------------------------------
const BEGIN = '/* @AQSMS-PURE-BEGIN */';
const END = '/* @AQSMS-PURE-END */';

function extract(inoPath) {
    const src = readFileSync(inoPath, 'utf8');

    const b = src.indexOf(BEGIN);
    const e = src.indexOf(END);
    if (b < 0 || e < 0 || e <= b) {
        throw new Error(`PURE LOGIC markers not found in ${inoPath}. ` +
                        `The extraction cannot proceed; fix the markers first.`);
    }
    const region = src.slice(b + BEGIN.length, e).trim();

    const grab = (re, what) => {
        const m = src.match(re);
        if (!m) throw new Error(`Could not find ${what} in ${inoPath} — ` +
                                `the tests depend on it and must not guess.`);
        return m[0].trim();
    };

    const stateDefines = [...src.matchAll(/^#define (?:SMS|SIM)_[A-Z_]+\s+\d+\s*$/gm)]
        .map(m => m[0].trim());
    if (stateDefines.length < 12) {
        throw new Error(`Expected 5 SMS_ and 7 SIM_ state defines, found ` +
                        `${stateDefines.length}. Refusing to test a partial set.`);
    }

    const cdsStruct = grab(/^struct CdsReport \{[\s\S]*?\n\};/m, 'struct CdsReport');

    return [
        '// GENERATED by firmware/tests/run-regression.mjs — do not edit.',
        '// Extracted verbatim from aqsms_esp32.ino.',
        '#include <stdint.h>',
        '',
        grab(/^#define AQSMS_EVENT_ID_MAX\s+\d+\s*$/m, 'AQSMS_EVENT_ID_MAX'),
        grab(/^#define AQSMS_EVENT_ID_BUF\s+\d+\s*$/m, 'AQSMS_EVENT_ID_BUF'),
        '',
        ...stateDefines,
        '',
        cdsStruct,
        '',
        region,
        '',
    ].join('\n');
}

// ---------------------------------------------------------------------------
// 3. The test cases.  Compiled together with the extracted region.
// ---------------------------------------------------------------------------
const DRIVER = String.raw`
#include "pure_logic.cpp"

static char g_log[65536];
static int  g_log_n = 0;
static int  g_pass  = 0;
static int  g_fail  = 0;

static void L(const char *s) {
    for (int i = 0; s[i] && g_log_n < (int)sizeof(g_log) - 1; i++) g_log[g_log_n++] = s[i];
    g_log[g_log_n] = 0;
}
static void LI(long v) {
    char t[16]; int k = 0;
    if (v < 0) { L("-"); v = -v; }
    if (v == 0) { L("0"); return; }
    while (v > 0 && k < 15) { t[k++] = (char)('0' + (v % 10)); v /= 10; }
    while (k > 0) { char c[2]; c[0] = t[--k]; c[1] = 0; L(c); }
}
static bool same(const char *a, const char *b) {
    int i = 0;
    for (; a[i] && b[i]; i++) if (a[i] != b[i]) return false;
    return a[i] == 0 && b[i] == 0;
}
static void ok(bool cond, const char *name) {
    if (cond) { g_pass++; L("  ok    "); } else { g_fail++; L("  FAIL  "); }
    L(name); L("\n");
}
static void section(const char *name) { L("\n"); L(name); L("\n"); }

extern "C" int  aqsms_tests_run();
extern "C" char *aqsms_log_ptr() { return g_log; }
extern "C" int  aqsms_log_len() { return g_log_n; }
extern "C" int  aqsms_pass_count() { return g_pass; }

extern "C" int aqsms_tests_run() {
    g_log_n = 0; g_pass = 0; g_fail = 0;

    /* =====================================================================
     * A. SMS delivery state — one vocabulary everywhere (fix 2)
     * ===================================================================== */
    section("A. SMS delivery state");
    ok(!same(sms_state_name(SMS_DELIVERED), "failed"),
       "delivered is NEVER displayed as failed (the reported bug)");
    ok(same(sms_state_name(SMS_DELIVERED), "delivered"),
       "delivered displays as \"delivered\"");
    ok(same(sms_state_name(SMS_FAILED), "failed"), "failed displays as \"failed\"");
    ok(same(sms_state_name(SMS_SUBMITTED), "submitted"), "submitted displays as \"submitted\"");
    ok(same(sms_state_name(SMS_ACCEPTED), "accepted"), "accepted displays as \"accepted\"");
    ok(same(sms_state_name(SMS_NOT_ATTEMPTED), "not attempted"),
       "not attempted displays as \"not attempted\"");

    ok(!same(sms_state_name(SMS_NOT_ATTEMPTED), sms_state_name(SMS_FAILED)) &&
       !same(sms_state_name(SMS_FAILED),        sms_state_name(SMS_SUBMITTED)) &&
       !same(sms_state_name(SMS_SUBMITTED),     sms_state_name(SMS_ACCEPTED)) &&
       !same(sms_state_name(SMS_ACCEPTED),      sms_state_name(SMS_DELIVERED)),
       "all five states have distinct names");

    ok(SMS_NOT_ATTEMPTED < SMS_FAILED && SMS_FAILED < SMS_SUBMITTED &&
       SMS_SUBMITTED < SMS_ACCEPTED && SMS_ACCEPTED < SMS_DELIVERED,
       "states are ordered weakest-to-strongest (so max() = best result)");

    ok(sms_state_merge(SMS_DELIVERED, SMS_FAILED) == SMS_DELIVERED,
       "a later weaker result cannot downgrade a delivery");
    ok(sms_state_merge(SMS_FAILED, SMS_DELIVERED) == SMS_DELIVERED,
       "merge is order-independent");
    ok(sms_state_merge(SMS_NOT_ATTEMPTED, SMS_ACCEPTED) == SMS_ACCEPTED,
       "accepted beats not-attempted");
    ok(sms_state_merge(SMS_NOT_ATTEMPTED, SMS_NOT_ATTEMPTED) == SMS_NOT_ATTEMPTED,
       "merge of two non-attempts stays not-attempted");
    ok(sms_state_merge(SMS_ACCEPTED, SMS_DELIVERED) == SMS_DELIVERED,
       "one recipient delivering wins over another merely accepting");

    /* =====================================================================
     * B. AT+CPIN? classification (fix 3)
     * ===================================================================== */
    section("B. AT+CPIN? classification");
    ok(cpin_classify("+CPIN: READY", true, "", false, false) == SIM_READY,
       "r\"+CPIN: READY\" -> READY");
    ok(cpin_classify("OK", true, "", false, false) != SIM_READY,
       "the final \"OK\" line is NOT read as READY (the reported bug)");
    ok(cpin_classify("OK", true, "", false, false) == SIM_UNKNOWN,
       "\"OK\" alone classifies as UNKNOWN, not as a healthy SIM");
    ok(cpin_classify("+CPIN: SIM PIN", true, "", false, false) == SIM_PIN_REQUIRED,
       "r\"+CPIN: SIM PIN\" -> SIM PIN REQUIRED");
    ok(cpin_classify("+CPIN: SIM PUK", true, "", false, false) == SIM_PUK_REQUIRED,
       "r\"+CPIN: SIM PUK\" -> SIM PUK REQUIRED (not PIN)");
    ok(cpin_classify("+CPIN: NOT INSERTED", true, "", false, false) == SIM_NOT_INSERTED,
       "\"+CPIN: NOT INSERTED\" -> SIM NOT INSERTED");
    ok(cpin_classify("+CPIN: NOT READY", true, "", false, false) == SIM_NOT_INSERTED,
       "\"+CPIN: NOT READY\" -> SIM NOT INSERTED, never READY");
    ok(cpin_classify("+CPIN: something new", true, "", false, false) == SIM_UNKNOWN,
       "an unrecognised +CPIN line is never promoted to READY");
    ok(cpin_classify("+CPIN: SIM PIN2", true, "", false, false) == SIM_PIN_REQUIRED,
       "SIM PIN2 is a PIN requirement too");
    ok(cpin_classify("+CPIN: SIM PUK2", true, "", false, false) == SIM_PUK_REQUIRED,
       "SIM PUK2 is a PUK requirement too");
    ok(cpin_classify("+CPIN: READY\r", true, "", false, false) == SIM_READY,
       "a trailing carriage return does not hide READY");
    ok(cpin_classify("+CPIN: READY EXTRA", true, "", false, false) == SIM_UNKNOWN,
       "trailing junk does not turn an unknown answer into READY");

    ok(cpin_classify("", false, "+CME ERROR: 10", true, false) == SIM_NOT_INSERTED,
       "+CME ERROR: 10 -> SIM NOT INSERTED");
    ok(cpin_classify("", false, "+CME ERROR: 13", true, false) == SIM_ERROR,
       "+CME ERROR: 13 -> SIM ERROR");
    ok(cpin_classify("", false, "+CME ERROR: SIM not inserted", true, false) == SIM_NOT_INSERTED,
       "text form of the not-inserted error is matched too");
    ok(cpin_classify("", false, "ERROR", true, false) == SIM_ERROR,
       "bare ERROR -> SIM ERROR");
    ok(cpin_classify("", false, "+CME ERROR: 100", true, false) != SIM_NOT_INSERTED,
       "error 100 is not read as error 10 (codes are matched exactly)");
    ok(cpin_classify("", false, "+CME ERROR: 130", true, false) != SIM_NOT_INSERTED,
       "error 130 is not read as error 13");
    ok(cpin_classify("", false, "+CMS ERROR: 10", true, false) == SIM_NOT_INSERTED,
       "the +CMS text of the same code is handled");
    ok(cpin_classify("", false, "+CME ERROR: SIM PIN required", true, false) == SIM_PIN_REQUIRED,
       "a text-form PIN error is classified as PIN required, not as generic ERROR");
    ok(cpin_classify("", false, "+CME ERROR: SIM PUK required", true, false) == SIM_PUK_REQUIRED,
       "a text-form PUK error is classified as PUK required");
    ok(cpin_classify("", false, "", false, true) == SIM_TIMEOUT,
       "no answer at all -> SIM TIMEOUT (not ERROR, not READY)");
    ok(cpin_classify("", false, "", false, false) == SIM_UNKNOWN,
       "nothing observed at all -> UNKNOWN");

    ok(!same(sim_state_name(SIM_PIN_REQUIRED), sim_state_name(SIM_PUK_REQUIRED)) &&
       !same(sim_state_name(SIM_NOT_INSERTED), sim_state_name(SIM_TIMEOUT)),
       "the four SIM problems get four different names");

    /* =====================================================================
     * C. +CDS delivery reports (fix 5)
     * ===================================================================== */
    section("C. +CDS delivery report parsing");
    {
        CdsReport r;

        ok(cds_parse("+CDS: 5,0,,,\"26/10/09,12:30:00+32\",\"26/10/09,12:30:05+32\",0", r)
           && r.valid && r.mr == 0 && r.has_st && r.st == 0,
           "quoted text-mode report with <st>=0 -> mr 0, status 0, delivered");

        /* The reported bug: with no <st> field the old lastIndexOf(',') read a
         * piece of the <dt> timestamp and reported a bogus status. */
        ok(cds_parse("+CDS: 5,0,,,\"26/10/09,12:30:00+32\",\"26/10/09,12:30:05+32\"", r)
           && r.valid && r.mr == 0 && !r.has_st,
           "report with NO <st> yields no status (old code read 12 out of the timestamp)");

        ok(cds_parse("+CDS: 5,0,,,26/10/09,12:30:00+32,26/10/09,12:30:05+32,0", r)
           && r.valid && r.mr == 0 && r.has_st && r.st == 0,
           "unquoted time fields parse the same way");

        ok(cds_parse("+CDS: 5,0,,,26/10/09,12:30:00+32,26/10/09,12:30:05+32", r)
           && r.valid && r.mr == 0 && !r.has_st,
           "unquoted time fields with no <st> also yield no status");

        ok(cds_parse("+CDS: 5,17,,,\"26/10/09,12:30:00+32\",\"26/10/09,12:30:05+32\",0", r)
           && r.valid && r.mr == 17 && r.st == 0,
           "the message reference is read so a report can be correlated");

        ok(cds_parse("+CDS: 5,3,,,\"26/10/09,12:30:00+32\",\"26/10/09,12:30:05+32\",1", r)
           && r.valid && r.has_st && r.st == 1,
           "a non-zero status is reported as its real value, not as delivered");

        ok(cds_parse("+CDS: 5,0,,,\"26/10/09,12:30:00+32\",\"26/10/09,12:30:05+32\",0", r)
           && r.mr != 3,
           "a report for ref 0 is not confused with another reference");

        ok(!cds_parse("+CMGS: 12", r), "a +CMGS line is not mistaken for a report");
        ok(!cds_parse("OK", r), "\"OK\" is not mistaken for a report");
        ok(!cds_parse("+CDS:", r), "an empty report body is rejected");

        ok(cds_parse("+CDS: 5,0", r) && !r.has_st,
           "a truncated report cannot invent a status");
    }

    /* =====================================================================
     * D. Stable event ids (fix 1)
     * ===================================================================== */
    section("D. Stable alert event ids");
    {
        char a[AQSMS_EVENT_ID_BUF];
        char b[AQSMS_EVENT_ID_BUF];
        char c[AQSMS_EVENT_ID_BUF];

        event_id_build(a, sizeof(a), "esp32-pond-1", 0xDEADBEEFu, 17);
        ok(same(a, "esp32-pond-1-deadbeef-17"),
           "the id has the documented shape <device>-<nonce>-<seq>");

        event_id_build(b, sizeof(b), "esp32-pond-1", 0xDEADBEEFu, 17);
        ok(same(a, b), "the same alert built twice gives the same id (retry-safe)");

        event_id_build(c, sizeof(c), "esp32-pond-1", 0xDEADBEEFu, 18);
        ok(!same(a, c), "a different alert sequence gives a different id");
        event_id_build(c, sizeof(c), "esp32-pond-1", 0x00000001u, 17);
        ok(!same(a, c), "a different nonce gives a different id");

        ok(event_id_valid(a), "the built id satisfies the Pi's event_id rule");
        ok(aqsms_len(a) <= AQSMS_EVENT_ID_MAX,
           "the built id is within the server's 128-character limit");
        ok(aqsms_len(a) < AQSMS_EVENT_ID_BUF,
           "the built id fits the stored buffer with its terminator");

        /* A device id is operator-supplied and is interpolated into hand-built
         * JSON, so unsafe characters must not survive into the id. */
        event_id_build(a, sizeof(a), "bad\"id\\name here", 1u, 1);
        ok(event_id_valid(a), "a device id with quotes/backslashes still yields a valid id");
        ok(same(a, "bad_id_name_here-00000001-1"),
           "unsafe device-id characters are replaced, not emitted");

        /* Over-long device id must be truncated, never overflow the buffer. */
        {
            char big[200];
            for (int i = 0; i < 190; i++) big[i] = 'x';
            big[190] = 0;
            event_id_build(a, sizeof(a), big, 0u, 0);
            ok(event_id_valid(a), "an over-long device id still yields a valid id");
            ok(aqsms_len(a) < AQSMS_EVENT_ID_BUF, "an over-long device id cannot overflow the buffer");
            ok(a[AQSMS_EVENT_ID_BUF - 1] == 0, "the built id is always NUL-terminated");
        }

        /* The rule itself, checked against the server's own stated limits. */
        ok(!event_id_valid(""), "the server rejects an empty id, and so does this");
        ok(!event_id_valid("   "), "a whitespace-only id is rejected");
        ok(!event_id_valid(" leading"), "a leading space is rejected (the server would strip it)");
        ok(!event_id_valid("trailing "), "a trailing space is rejected");
        ok(!event_id_valid("has\"quote"), "a double quote is rejected (it would corrupt the JSON)");
        ok(!event_id_valid("has\\slash"), "a backslash is rejected (it would corrupt the JSON)");
        ok(!event_id_valid("has\nnewline"), "a control character is rejected");

        {
            char e128[140];
            for (int i = 0; i < 128; i++) e128[i] = 'a';
            e128[128] = 0;
            ok(event_id_valid(e128), "exactly 128 characters is accepted (MAX_EVENT_ID_LENGTH)");
            e128[128] = 'a'; e128[129] = 0;
            ok(!event_id_valid(e128), "129 characters is rejected");
        }
    }

    L("\n");
    L("-----------------------------------------\n");
    L("  passed: "); LI(g_pass); L("\n");
    L("  failed: "); LI(g_fail); L("\n");
    L("-----------------------------------------\n");
    return g_fail;
}
`;

// ---------------------------------------------------------------------------
// 4. Build and run.
// ---------------------------------------------------------------------------
function main() {
    const clang = findClang();
    const dir = mkdtempSync(join(tmpdir(), 'aqsms-regress-'));
    const purePath = join(dir, 'pure_logic.cpp');
    const driverPath = join(dir, 'test_driver.cpp');
    const wasmPath = join(dir, 'tests.wasm');

    writeFileSync(purePath, extract(INO), 'utf8');
    writeFileSync(driverPath, DRIVER, 'utf8');

    const args = [
        '--target=wasm32',
        '-std=c++17',
        '-O1',
        '-nostdlib',
        '-fno-exceptions',
        '-fno-rtti',
        '-Wall',
        '-Wextra',
        '-Wno-unused-parameter',
        '-I', dir,
        '-Wl,--no-entry',
        '-Wl,--export-all',
        '-Wl,--allow-undefined',
        '-Wl,--export-memory',
        '-o', wasmPath,
        driverPath,
    ];

    try {
        execFileSync(clang, args, { stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (err) {
        const out = [err.stdout?.toString(), err.stderr?.toString()].filter(Boolean).join('\n');
        console.error('COMPILE FAILED — the extracted pure-logic region did not build.\n');
        console.error(out || err.message);
        console.error(`\nGenerated sources kept at: ${dir}`);
        process.exit(2);
    }

    const bytes = readFileSync(wasmPath);

    // Shims: the compiler may lower a struct/array operation to a libc call
    // even in freestanding code.  These are the only imports expected.
    const imports = {
        env: {
            memcpy(dst, src, n) { new Uint8Array(memory.buffer).copyWithin(dst, src, src + n); return dst; },
            memmove(dst, src, n) { new Uint8Array(memory.buffer).copyWithin(dst, src, src + n); return dst; },
            memset(dst, c, n) { new Uint8Array(memory.buffer).fill(c & 0xff, dst, dst + n); return dst; },
        },
    };
    let memory;

    return WebAssembly.instantiate(bytes, imports).then(({ instance }) => {
        memory = instance.exports.memory;
        const failures = instance.exports.aqsms_tests_run();
        const len = instance.exports.aqsms_log_len();
        const ptr = instance.exports.aqsms_log_ptr();
        const log = new TextDecoder().decode(new Uint8Array(memory.buffer, ptr, len));

        console.log('AQSMS ESP32 — pure-logic regression tests');
        console.log('source : aqsms_esp32.ino (extracted PURE LOGIC region, not a copy)');
        console.log('clang  : ' + clang);
        console.log('node   : ' + process.version);
        console.log(log);

        if (process.env.AQSMS_KEEP) {
            console.error(`Generated sources kept at: ${dir}`);
        }
        process.exit(failures === 0 ? 0 : 1);
    }).catch((err) => {
        console.error('Could not instantiate the test module:');
        console.error(err);
        process.exit(3);
    });
}

main();
