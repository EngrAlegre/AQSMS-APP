/**
 * Bundles the Pi's local CA certificate into the Android app.
 *
 * The Pi serves HTTPS with a certificate signed by its own private CA (see
 * pi-server/make-cert.sh). Android does not trust that CA by default, so the
 * app declares it as an extra trust anchor. The result is certificate pinning
 * to one specific Pi: no public CA, no domain name, no port forwarding.
 *
 * Input:  frontend/certs/aqsms-ca.crt   (public certificate only)
 * Output: android/app/src/main/res/raw/pi_server_ca
 *         android/app/src/main/res/xml/network_security_config.xml
 *         and the matching android:networkSecurityConfig attribute
 *
 * If the certificate file is absent this plugin does nothing and the build
 * still succeeds -- an APK with no pinned CA is preferable to a broken build.
 * The app will simply not trust the Pi's HTTPS until the certificate is added
 * and the APK is rebuilt.
 */
const { withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");

/** Path to the exported CA certificate, relative to the app project root. */
const CERT_SOURCE = "certs/aqsms-ca.crt";
/** Name of the copied file under res/raw. Must be a valid Android resource
 *  name: lowercase, digits and underscores only, so no ".crt" suffix. */
const RAW_NAME = "pi_server_ca";
const NSC_XML_NAME = "network_security_config";

// NOTE: an XML comment may not contain a double hyphen -- the XML spec reserves
// "--" for the comment delimiters themselves, and AAPT rejects the file with
// "The string \"--\" is not permitted within comments." Do not reintroduce one
// (a "--" separator, or a "--" in prose) anywhere in the comment below.
const NSC_XML = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-pi-certificate.js (do not edit by hand).

  Trusts the AQSMS Pi's own certificate authority in addition to the system
  roots, so the app can talk to https://<pi-address>:8443/ over the local
  Wi-Fi without a public certificate or a domain name.

  Cleartext is still permitted: during initial setup the app may be pointed at
  the Pi before its certificate has been installed, and the app itself warns
  the farmer when the saved address is plain http.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
            <certificates src="@raw/${RAW_NAME}" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;

function missingCertWarning() {
  return [
    "",
    "! with-pi-certificate: frontend/certs/aqsms-ca.crt was not found.",
    "! The APK will be built WITHOUT trusting your Pi's HTTPS certificate.",
    "! To fix: run pi-server/make-cert.sh on the Pi, copy certs/aqsms-ca.crt",
    "! into frontend/certs/, and rebuild. Plain HTTP is unaffected.",
    "",
  ].join("\n");
}

/** Copy the CA into res/raw and write the network security config. */
const withPiCertificateFiles = (config) =>
  withDangerousMod(config, [
    "android",
    async (cfg) => {
      const source = path.join(cfg.modRequest.projectRoot, CERT_SOURCE);
      if (!fs.existsSync(source)) {
        console.warn(missingCertWarning());
        return cfg;
      }

      const mainDir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main");
      const rawDir = path.join(mainDir, "res", "raw");
      const xmlDir = path.join(mainDir, "res", "xml");
      fs.mkdirSync(rawDir, { recursive: true });
      fs.mkdirSync(xmlDir, { recursive: true });

      fs.copyFileSync(source, path.join(rawDir, RAW_NAME));
      fs.writeFileSync(path.join(xmlDir, `${NSC_XML_NAME}.xml`), NSC_XML, "utf8");
      console.log(`with-pi-certificate: bundled ${CERT_SOURCE} as @raw/${RAW_NAME}`);
      return cfg;
    },
  ]);

/**
 * Point <application> at the config written above. Skipped when the CA is
 * absent, because referencing an @raw resource that was never written would
 * fail the Android resource step.
 */
const withPiCertificateManifest = (config) =>
  withAndroidManifest(config, (cfg) => {
    const source = path.join(cfg.modRequest.projectRoot, CERT_SOURCE);
    if (!fs.existsSync(source)) return cfg;

    const app = cfg.modResults.manifest.application?.[0];
    if (!app) return cfg;
    app.$["android:networkSecurityConfig"] = `@xml/${NSC_XML_NAME}`;
    return cfg;
  });

module.exports = (config) =>
  withPiCertificateManifest(withPiCertificateFiles(config));
